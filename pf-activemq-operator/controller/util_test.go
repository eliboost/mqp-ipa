// UninstallCertManager uninstalls the cert manager
func UninstallCertManager(t *testing.T) {
	cmd := exec.Command("kubectl", "delete", "-f", certmanagerURL)
	if err := cmd.Run(); err != nil {
		t.Error(err)
	}
}

