func createKubeconfigFileForRestConfig(restConfig rest.Config) string {
	clusters := make(map[string]*clientcmdapi.Cluster)
	clusters["default-cluster"] = &clientcmdapi.Cluster{
		Server:                   restConfig.Host,
		CertificateAuthorityData: restConfig.CAData,
	}
	contexts := make(map[string]*clientcmdapi.Context)
	contexts["default-context"] = &clientcmdapi.Context{
		Cluster:  "default-cluster",
		AuthInfo: "default-user",
	}
	authinfos := make(map[string]*clientcmdapi.AuthInfo)
	authinfos["default-user"] = &clientcmdapi.AuthInfo{
		ClientCertificateData: restConfig.CertData,
		ClientKeyData:         restConfig.KeyData,
	}
	clientConfig := clientcmdapi.Config{
		Kind:           "Config",
		APIVersion:     "v1",
		Clusters:       clusters,
		Contexts:       contexts,
		CurrentContext: "default-context",
		AuthInfos:      authinfos,
	}
	kubeConfigFile, _ := os.CreateTemp("", "kubeconfig")
	_ = clientcmd.WriteToFile(clientConfig, kubeConfigFile.Name())
	return kubeConfigFile.Name()
}

// installRequiredTestRunFiles install files which normally are generated by the others controllers
// e.g. cert-manager
func installRequiredTestRunFiles(admin *envtest.AuthenticatedUser, name string, template string) error {
	file, err := os.CreateTemp("", "activemq-operator-test-files-*.yaml")
	if err != nil {
		return err
	}

	defer os.Remove(file.Name())

	bytes, err := os.ReadFile("../testfiles/testrun/" + template)
	if err != nil {
		return err
	}

	data := strings.ReplaceAll(string(bytes), "%%replace%%", name)

	_, err = file.WriteString(data)
	if err != nil {
		return err
	}

	err = file.Close()
	if err != nil {
		return err
	}

	if err := kubeCreate(admin, file.Name()); err != nil {
		return err
	}

	return nil
}
